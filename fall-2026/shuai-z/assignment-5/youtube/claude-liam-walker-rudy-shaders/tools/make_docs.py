#!/usr/bin/env python3
"""Write SHOTLIST.md, COMPONENTS.md, PROMPTS.md and RIFF.md from the beat sheet
and the two ledgers in checks/, so the paperwork cannot drift from the film.

    python3 tools/make_docs.py
"""
import json
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
sheet = json.loads((REEL / "beat_sheet.json").read_text())
ledgers = {p: json.loads((REEL / f"checks/{p}/gamedev-evidence.json").read_text()) for p in ("game", "godot")}
beats = sheet["beats"]
title = sheet["metadata"]["title"]

NEXT = {  # one suggested experiment per evidence beat (RIFF.md)
    "B02": "Pause the game in a window during a hit and compare the corner with this frame: is the tint the first thing the eye finds?",
    "B06": "Set tint_amount to 0.25 in the capture tool and predict P1 by hand first: 200 + 0.1 × (153 − 200) for red.",
    "B08": "Play it yourself at 30 fps (--fixed-fps 30) and count the frames the tint shows after one hit: the brief says 35 or 36.",
    "B09": "Stand on the spikes when a window ends (the brief's predicted failure 6) and watch how short the 0.0 gap is.",
    "B12": "Add a second light low on the right in a copy of the scene and sweep normal_strength again: does it become visible?",
    "B14": "Orbit with the circle's albedo_tint set to white in memory, and compare the disc with the waystone face for face.",
    "B16": "Predict quad B for a 32-grey texel by hand before adding it to the strip.",
    "B18": "Change uv_scale in one material only and check, by the same measure, that the other stone stays at 0.00.",
    "B19": "Convert the circle's material to a StandardMaterial3D's code and find which uniform holds its tint.",
    "B21": "Run the test at 20 fps: does A9 still pass with a 0.05 s tolerance?",
    "B22": "Change hint_range(0.0, 1.0) to (0.0, 2.0) on tint_amount in a copy and predict which check fails.",
    "B23": "Take the OS screenshot on a display set to sRGB and see whether the four-to-eleven-step gap closes.",
}


def dur(b):
    return b.get("actual_duration_s") or 0.0


def visual(b):
    s = b["shot"]
    if s.get("capture_plan"):
        cp = s["capture_plan"]
        segs = ", ".join(f"{x['from']}–{x['to'] - 1}" + (f" at {x['speed']:.2g}×" if x["speed"] != 1.0 else "") for x in cp["segments"])
        hold = cp.get("held_final_frames", 0)
        return f"capture `{cp['capture']}` frames {segs}" + (f" + held {hold} f" if hold else "")
    if s.get("still_plan"):
        return f"still `{s['still_plan']['image']}`"
    r = s["remotion"]
    p = r["props"]
    extra = f" `{b['excerpt']['project']}/{b['excerpt']['path']}:{b['excerpt']['start_line']}–{b['excerpt']['end_line']}`" if b.get("excerpt") else ""
    img = f" `{p['image'].rsplit('/', 1)[-1]}`" if p.get("image") else ""
    return f"{r['pattern']}" + (f" ({p.get('mode')})" if p.get("mode") else "") + extra + img


t = 0.0
rows = []
for b in beats:
    rows.append(f"| {b['beat_id']} | {t:6.1f} | {dur(b):5.1f} | {b['act']} | {visual(b)} |")
    t += dur(b)
(REEL / "SHOTLIST.md").write_text(
    f"# SHOTLIST — {title}\n\n{len(beats)} beats, {t:.1f} s ({int(t // 60)}:{t % 60:04.1f}), 3840×2160, 30 fps. "
    "Generated by `tools/make_docs.py` from `beat_sheet.json`.\n\n"
    "Every Godot code beat is followed by its visible result (`code-then-result-v1`). The engine footage is the two hashed Movie Maker takes "
    "(CAPTURE.md); the stills are windowed engine captures from `evidence/use-it/` or recorded logs, labelled on screen.\n\n"
    "| Beat | Start s | Dur s | Act | Visual |\n| --- | ---: | ---: | --- | --- |\n" + "\n".join(rows) + "\n")

out = [f"# COMPONENTS — {title}\n",
       "Two Godot projects, two ledgers: the course checker takes one folder holding `project.godot`, so each project has its own "
       "`checks/<project>/gamedev-evidence.json` (see `tools/make_evidence.py`). `.uid` identifiers and `.godot/` are left out by the contract.\n"]
for p, ev in ledgers.items():
    out.append(f"## `{p}/` at `{ev['game']['revision'][:7]}` — {len(ev['files'])} files in components, {len(ev['exclusions'])} excluded\n")
    out.append("| Component | Files | Beats | What it does |\n| --- | ---: | --- | --- |")
    for c in ev["components"]:
        out.append(f"| `{c['id']}` | {len(c['files'])} | {', '.join(c['beat_ids'])} | {c['explanation']} |")
    out.append("\n| Code beat | Source | Result beat | Observed |\n| --- | --- | --- | --- |")
    ex = {e["beat_id"]: e for e in ev["excerpts"]}
    for pr in ev["code_result_pairs"]:
        e = ex[pr["code_beat"]]
        out.append(f"| {pr['code_beat']} | `{e['path']}:{e['start_line']}–{e['end_line']}` | {pr['result_beat']} | {pr['observation']} |")
    reasons = {}
    for x in ev["exclusions"]:
        reasons.setdefault(x["reason"], []).append(x["path"])
    if reasons:
        out.append("\n**Excluded, with the reason recorded in the ledger:**\n")
        for r, paths in reasons.items():
            shown = ", ".join(f"`{q}`" for q in paths[:6]) + (f" and {len(paths) - 6} more" if len(paths) > 6 else "")
            out.append(f"- {len(paths)} file(s): {shown}. {r}")
    out.append("")
out.append("## Shown on still cards rather than as Workbench excerpts\n\n"
           "- `godot/shaders/standard_generated.gdshader` lines 10–11 and 69–72, beside `weathered_stone.gdshader` lines 3–4 and 19–20 (B19): "
           "`tools/make_stills.py` reads the lines from the files.\n"
           "- `CHANGE-BRIEF.md` section 2's uniform table and colour line (B04), read from the file; the rows are asserted against it.\n")
(REEL / "COMPONENTS.md").write_text("\n".join(out) + "\n")

pr = [f"# PROMPTS — {title}\n", "Every prompt shown or read in the film.\n"]
for b in beats:
    r = b["shot"].get("remotion", {})
    if r.get("pattern") == "ClaudeComposerAsk":
        p = r["props"]
        pr.append(f"## {b['beat_id']} — {p['greeting']}\n\n**Status:** {'reconstructed prompt — illustrative, not a transcript' if b['beat_id'] == 'B00' else 'suggested prompt for the viewer'}\n\n```text\n{p['command']}\n```\n")
        if p.get("output"):
            pr.append("On-screen result lines (each checked in FACTCHECK.md):\n\n" + "\n".join(f"- {o}" for o in p["output"]) + "\n")
pr.append("## The prompts behind the work shown\n\n"
          "The film quotes no prompt from the build sessions. The scoped `claude -p` prompts it refers to are in the assignment folder: "
          "`sessions/prompt-1.txt` (CLAUDE.md), `prompt-2.txt` and `prompt-2b.txt` (the driver and its test), `prompt-3.txt` (the materials audit), "
          "with their transcripts described in `sessions/README.md`.\n")
(REEL / "PROMPTS.md").write_text("\n".join(pr))

rf = [f"# RIFF — {title}\n",
      "Liam, in for Bear (Kokoro `am_onyx`). Observations come from the captures and the logs; mechanisms from the source named in the "
      "preceding beat. The judgment that the effects look right is shuai-z's (TEST-REPORT.md §§5–6), or Claude's at shuai-z's request where "
      "the film says so (§§7–8, 12).\n",
      "| Beat | Artifact | Visible observation | Interpretation (source) | Narration | Next experiment |",
      "| --- | --- | --- | --- | --- | --- |"]
for i, b in enumerate(beats):
    s = b["shot"]
    if not (s.get("capture_plan") or s.get("still_plan")):
        continue
    prev = beats[i - 1]
    src = (f"`{prev['excerpt']['project']}/{prev['excerpt']['path']}:{prev['excerpt']['start_line']}–{prev['excerpt']['end_line']}`"
           if prev.get("excerpt") else "TEST-REPORT.md, CHANGE-BRIEF.md")
    rf.append(f"| {b['beat_id']} | {visual(b)} | {s['observation']} | {src} | {b['narration_text']} | {NEXT.get(b['beat_id'], '')} |")
(REEL / "RIFF.md").write_text("\n".join(rf) + "\n")
print(f"docs written; film {t:.1f} s")
