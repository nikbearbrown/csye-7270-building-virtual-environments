#!/usr/bin/env python3
"""Write SHOTLIST.md, COMPONENTS.md, PROMPTS.md and RIFF.md from the beat sheet
and gamedev-evidence.json, so the paperwork cannot drift from the film.

    python3 tools/make_docs.py
"""
import json
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
sheet = json.loads((REEL / "beat_sheet.json").read_text())
ev = json.loads((REEL / "gamedev-evidence.json").read_text())
beats = sheet["beats"]
title = sheet["metadata"]["title"]

NEXT = {  # one suggested experiment per evidence beat (RIFF.md)
    "B05": "Ask Claude for the same ring with 6 sides and predict the triangle count (4n − 4 per cylinder) before it reports.",
    "B06": "Look at the ring from directly above with look: does the stone-coloured disc stand 0.002 m in front of the ring, as the code says?",
    "B07": "Repeat the hand edit with G, Z, 0.034, Enter instead of a drag, and compare the read-back Z with 0.4537.",
    "B11": "Orbit again with the post moved next to the waystone: does the waystone still read as chest-high on a 1.2 m figure?",
    "B13": "Change one number in BRIEF (say the spikes' height to 0.50) and run the check: which line fails, and does the exit code change?",
    "B15": "Lower the waystone 0.3 m into the floor instead: does the same check catch a sinking prop as well as a floating one?",
}


def dur(b):
    return b.get("actual_duration_s") or 0.0


def visual(b):
    s = b["shot"]
    if s.get("capture_plan"):
        cp = s["capture_plan"]
        segs = ", ".join(f"{x['from']}–{x['to'] - 1}" for x in cp["segments"])
        hold = cp.get("held_final_frames", 0)
        return f"`capture/{cp['capture']}.mp4` frames {segs}" + (f" + held {hold} f" if hold else "")
    if s.get("still_plan"):
        return f"still `{s['still_plan']['image']}`"
    r = s["remotion"]
    p = r["props"]
    extra = f" `{b['excerpt']['path']}:{b['excerpt']['start_line']}–{b['excerpt']['end_line']}`" if b.get("excerpt") else ""
    img = f" `{p['image'].rsplit('/', 1)[-1]}`" if p.get("image") else ""
    return f"{r['pattern']}" + (f" ({p.get('mode')})" if p.get("mode") else "") + extra + img


t = 0.0
rows = []
for b in beats:
    rows.append(f"| {b['beat_id']} | {t:6.1f} | {dur(b):5.1f} | {b['act']} | {visual(b)} |")
    t += dur(b)
(REEL / "SHOTLIST.md").write_text(
    f"# SHOTLIST — {title}\n\n{len(beats)} beats, {t:.1f} s ({int(t // 60)}:{t % 60:04.1f}), 3840×2160, 30 fps. "
    "Generated by `tools/make_docs.py` from `beat_sheet.json`.\n\n"
    "Every Godot code beat is followed by its visible result (`code-then-result-v1`). The engine footage is the hashed Movie Maker take "
    "(CAPTURE.md); Blender images are the MCP look tool's or shuai-z's own screenshots, labelled on screen.\n\n"
    "| Beat | Start s | Dur s | Act | Visual |\n| --- | ---: | ---: | --- | --- |\n" + "\n".join(rows) + "\n")

comp = ["| Component | Files | Beats | What it does |", "| --- | ---: | --- | --- |"]
for c in ev["components"]:
    comp.append(f"| `{c['id']}` | {len(c['files'])} | {', '.join(c['beat_ids'])} | {c['explanation']} |")
pairs = ["| Code beat | Source | Result beat | Observed |", "| --- | --- | --- | --- |"]
ex = {e["beat_id"]: e for e in ev["excerpts"]}
for p in ev["code_result_pairs"]:
    e = ex[p["code_beat"]]
    pairs.append(f"| {p['code_beat']} | `{e['path']}:{e['start_line']}–{e['end_line']}` | {p['result_beat']} | {p['observation']} |")
(REEL / "COMPONENTS.md").write_text(
    f"# COMPONENTS — {title}\n\nThe Godot project `assignment-3/godot/` at `{ev['game']['revision'][:7]}`: {len(ev['files'])} authored files "
    f"(`.uid` identifiers and `.godot/` excluded by the contract), every one assigned to a component in `gamedev-evidence.json`. No exclusions.\n\n"
    + "\n".join(comp) + "\n\n## Code → result pairs\n\n" + "\n".join(pairs)
    + "\n\n## Not shown as Godot code, and why\n\n"
    "- `project.godot`, `scenes/props_room.tscn`: the running scene is shown instead (B11); the `.tscn` is what `build_props_room.gd` (B10) writes.\n"
    "- `tests/capture_props.gd`: named in the verdict (BVD1) for its first-version bug; its screenshots are in TEST-REPORT.md, not in the film.\n"
    "- `.glb` and `.import` files: inventoried and hashed; shown as the running scene (B11) and measured by the check (B13).\n"
    "- The Blender code (`assignment-3/tools/blender/*.py`) is outside the Godot project, so the checker's excerpt contract does not cover it. "
    "B05 shows `build_waystone.py` lines 301–311 verbatim on a still card, followed by what it built (B06).\n")

pr = [f"# PROMPTS — {title}\n", "Every prompt shown or read in the film.\n"]
for b in beats:
    r = b["shot"].get("remotion", {})
    if r.get("pattern") == "ClaudeComposerAsk":
        p = r["props"]
        pr.append(f"## {b['beat_id']} — {p['greeting']}\n\n**Status:** {'reconstructed prompt — illustrative, not a transcript' if b['beat_id'] == 'B00' else 'suggested prompt for the viewer'}\n\n```text\n{p['command']}\n```\n")
        if p.get("output"):
            pr.append("On-screen result lines (each checked in FACTCHECK.md):\n\n" + "\n".join(f"- {o}" for o in p["output"]) + "\n")
pr.append("## B05, B07, B08 — shuai-z's prompts quoted from the build session\n\n"
          "Verbatim from the Claude Code session of 2026-10-13 (times EDT), with Claude's translation:\n\n"
          "- 20:07: “我把符文往上移了点，你看一下；但是我觉得符文变成大写字母R会好看点，你改一下试试，看下三角面数会不会超” "
          "[I moved the rune up a little, take a look; but I think the rune would look better as a capital R — try it, and see whether the triangle count goes over.]\n"
          "- 20:14 (shown in B05): “现在不好看，不用R，把符文换成一个圆环试试” [It does not look good now. No R — try turning the rune into a ring.]\n"
          "- 20:18: “改成12边，加Revision 2，然后圆环再细一点” [Make it 12 sides, add Revision 2, and make the ring a bit thinner.]\n\n"
          "These are shuai-z's own prompts, shown as such. The code Claude ran for each is in `assignment-3/tools/blender/build_waystone.py`.\n")
(REEL / "PROMPTS.md").write_text("\n".join(pr))

rf = [f"# RIFF — {title}\n",
      "Liam, in for Bear (Kokoro `am_onyx`). Observations come from the images, the capture and the logs; mechanisms from the source "
      "named in the preceding beat. Nothing here judges whether the props look good; that judgment is shuai-z's (TEST-REPORT.md).\n",
      "| Beat | Artifact | Visible observation | Interpretation (source) | Narration | Next experiment |",
      "| --- | --- | --- | --- | --- | --- |"]
for i, b in enumerate(beats):
    s = b["shot"]
    if not (s.get("capture_plan") or s.get("still_plan")):
        continue
    prev = beats[i - 1]
    src = (f"`{prev['excerpt']['path']}:{prev['excerpt']['start_line']}–{prev['excerpt']['end_line']}`" if prev.get("excerpt")
           else "`tools/blender/build_waystone.py:301–311`" if b["beat_id"] in ("B05", "B06") else "FRICTIONAL.md, CHANGE-BRIEF.md rev. 2")
    rf.append(f"| {b['beat_id']} | {visual(b)} | {s['observation']} | {src} | {b['narration_text']} | {NEXT.get(b['beat_id'], '')} |")
(REEL / "RIFF.md").write_text("\n".join(rf) + "\n")
print(f"docs written; film {t:.1f} s")
