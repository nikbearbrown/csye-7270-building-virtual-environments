#!/usr/bin/env python3
"""Write SHOTLIST.md, COMPONENTS.md, PROMPTS.md and RIFF.md from the beat sheet
and the ledger in checks/game/, so the paperwork cannot drift from the film.

    python3 tools/make_docs.py
"""
import json
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
sheet = json.loads((REEL / "beat_sheet.json").read_text())
ledgers = {p: json.loads((REEL / f"checks/{p}/gamedev-evidence.json").read_text()) for p in ("game",)}
beats = sheet["beats"]
title = sheet["metadata"]["title"]

NEXT = {  # one suggested experiment per evidence beat (RIFF.md)
    "B02": "Play a minute in the 1280 × 720 window and note which effect your eye finds first, and where.",
    "B06": "Capture the preview with Sparks' lifetime_randomness at 0.0 and predict frame 20 first: how many specks of the first burst?",
    "B08": "Count the streaks you can tell apart on frame 12 of r1 yourself, before reading Claude's 14–18.",
    "B10": "Mash slash yourself at --fixed-fps 30 and watch for the frames with two bursts: the log says four frames per pair here.",
    "B11": "Cut a goblin facing left and check that its sparks still outlive it, mirrored.",
    "B13": "Repeat Claude's no-dust diff on r0 frame 25 with a threshold of 10 levels instead of 20, and compare the counts.",
    "B14": "Predict r1's largest change by hand from the ramp's new colour against the grass strip (#8FA85E).",
    "B15": "Measure the r2 band's top on frames 13, 25, 40 and 46 yourself before reading TUNING.md's 21, 33, 34 and 32.",
    "B16": "Halve damping in a copy and predict the top at frame 25 with the same model first.",
    "B18": "Run with the camera's position smoothing off in a copy and see whether the trail reads longer on screen.",
    "B20": "Jump straight up without moving and check that no puff is born on the take-off tick.",
    "B22": "Pause while the trail is still fading after a stop, and check that the fade freezes too.",
    "B23": "Find where in particles_generated.gdshader damping would act, and which uniform feeds it.",
    "B25": "Run the state tests at 30 fps through the wrapper and see whether any tick-count check needs a different tolerance.",
    "B26": "Rename damping_max instead of damping_min and predict, from the save order, what the loaded range becomes.",
    "B27": "Repeat the Visual Profiler reading under Forward+ on a copy, and note whether the GPU column stays at 0.0 ms.",
    "B28": "Capture the mutated preview at r1's seeds and diff it against r1 frame 15 pixel by pixel.",
}


def dur(b):
    return b.get("actual_duration_s") or 0.0


def visual(b):
    s = b["shot"]
    if s.get("capture_plan"):
        cp = s["capture_plan"]
        segs = ", ".join(f"{x['from']}–{x['to'] - 1}" + (f" at {x['speed']:.2g}×" if x["speed"] != 1.0 else "") for x in cp["segments"])
        hold = cp.get("held_final_frames", 0)
        return f"capture `{cp['capture']}` frames {segs}" + (f" + held {hold} f" if hold else "")
    if s.get("still_plan"):
        return f"still `{s['still_plan']['image']}`"
    r = s["remotion"]
    p = r["props"]
    extra = f" `{b['excerpt']['project']}/{b['excerpt']['path']}:{b['excerpt']['start_line']}–{b['excerpt']['end_line']}`" if b.get("excerpt") else ""
    img = f" `{p['image'].rsplit('/', 1)[-1]}`" if p.get("image") else ""
    return f"{r['pattern']}" + (f" ({p.get('mode')})" if p.get("mode") else "") + extra + img


t = 0.0
rows = []
for b in beats:
    rows.append(f"| {b['beat_id']} | {t:6.1f} | {dur(b):5.1f} | {b['act']} | {visual(b)} |")
    t += dur(b)
(REEL / "SHOTLIST.md").write_text(
    f"# SHOTLIST — {title}\n\n{len(beats)} beats, {t:.1f} s ({int(t // 60)}:{t % 60:04.1f}), 3840×2160, 30 fps. "
    "Generated by `tools/make_docs.py` from `beat_sheet.json`.\n\n"
    "Every Godot code beat is followed by its visible result (`code-then-result-v1`). The engine footage is the hashed Movie Maker take "
    "`play-01` (CAPTURE.md); the stills are the committed frame strips (fixture captures), Codex's Use It captures, or recorded logs, labelled on screen.\n\n"
    "| Beat | Start s | Dur s | Act | Visual |\n| --- | ---: | ---: | --- | --- |\n" + "\n".join(rows) + "\n")

out = [f"# COMPONENTS — {title}\n",
       "One Godot project, `game/`, one ledger: `checks/game/gamedev-evidence.json` (see `tools/make_evidence.py`). "
       "`.uid` identifiers and `.godot/` are left out by the contract.\n"]
for p, ev in ledgers.items():
    out.append(f"## `{p}/` at `{ev['game']['revision'][:7]}` — {len(ev['files'])} files in components, {len(ev['exclusions'])} excluded\n")
    out.append("| Component | Files | Beats | What it does |\n| --- | ---: | --- | --- |")
    for c in ev["components"]:
        out.append(f"| `{c['id']}` | {len(c['files'])} | {', '.join(c['beat_ids'])} | {c['explanation']} |")
    out.append("\n| Code beat | Source | Result beat | Observed |\n| --- | --- | --- | --- |")
    ex = {e["beat_id"]: e for e in ev["excerpts"]}
    for pr in ev["code_result_pairs"]:
        e = ex[pr["code_beat"]]
        out.append(f"| {pr['code_beat']} | `{e['path']}:{e['start_line']}–{e['end_line']}` | {pr['result_beat']} | {pr['observation']} |")
    reasons = {}
    for x in ev["exclusions"]:
        reasons.setdefault(x["reason"], []).append(x["path"])
    if reasons:
        out.append("\n**Excluded, with the reason recorded in the ledger:**\n")
        for r, paths in reasons.items():
            shown = ", ".join(f"`{q}`" for q in paths[:6]) + (f" and {len(paths) - 6} more" if len(paths) > 6 else "")
            out.append(f"- {len(paths)} file(s): {shown}. {r}")
    out.append("")
out.append("## Shown on still cards and figures rather than as Workbench excerpts\n\n"
           "- `game/shaders/particles_generated.gdshader` lines 10–11, 43, 139 and 311 beside the brief's velocity and gravity rows (B23), and "
           "`slash_sparks.tscn` lines 108, 79, 109 with the shader's line 311 (B03): `tools/make_stills.py` reads the lines from the files.\n"
           "- `CHANGE-BRIEF.md` sections 2 and 3, The intent (B04, B12): the timing-phase bullets are read from the file; the other rows are labelled as a summary.\n"
           "- Every number the strip cards quote from `TUNING.md` (B06, B08, B13–B16) is asserted to be in it by `tools/make_stills.py`.\n")
(REEL / "COMPONENTS.md").write_text("\n".join(out) + "\n")

pr = [f"# PROMPTS — {title}\n", "Every prompt shown or read in the film.\n"]
for b in beats:
    r = b["shot"].get("remotion", {})
    if r.get("pattern") == "ClaudeComposerAsk":
        p = r["props"]
        pr.append(f"## {b['beat_id']} — {p['greeting']}\n\n**Status:** {'reconstructed prompt — illustrative, not a transcript' if b['beat_id'] == 'B00' else 'suggested prompt for the viewer'}\n\n```text\n{p['command']}\n```\n")
        if p.get("output"):
            pr.append("On-screen result lines (each checked in FACTCHECK.md):\n\n" + "\n".join(f"- {o}" for o in p["output"]) + "\n")
pr.append("## The prompts behind the work shown\n\n"
          "The film quotes no prompt from the build sessions. The scoped `claude -p` prompts it refers to are in the assignment folder's `sessions/`: "
          "`prompt-1.txt` (CLAUDE.md), `prompt-2.txt` (Effect A, its configuration test and preview), `prompt-3.txt` and `prompt-3b.txt` (the plan and "
          "the wiring of Effect A, with its state test), `prompt-4.txt` (Effect B), `prompt-5.txt` and `prompt-5b.txt` (the plan and the wiring of "
          "Effect B), `prompt-6.txt` (the cost script), each beside its transcript `session-*.jsonl`.\n")
(REEL / "PROMPTS.md").write_text("\n".join(pr))

rf = [f"# RIFF — {title}\n",
      "Liam, in for Bear (Kokoro `am_onyx`). Observations come from the captures and the logs; mechanisms from the source named in the "
      "preceding beat. Every verdict on how an effect looks is shuai-z's (TUNING.md, TEST-REPORT.md \"Use It\"); Claude's strip readings "
      "and predictions are labelled as claims, and Codex's captures as Codex's.\n",
      "| Beat | Artifact | Visible observation | Interpretation (source) | Narration | Next experiment |",
      "| --- | --- | --- | --- | --- | --- |"]
for i, b in enumerate(beats):
    s = b["shot"]
    if not (s.get("capture_plan") or s.get("still_plan")):
        continue
    prev = beats[i - 1]
    src = (f"`{prev['excerpt']['project']}/{prev['excerpt']['path']}:{prev['excerpt']['start_line']}–{prev['excerpt']['end_line']}`"
           if prev.get("excerpt") else "TUNING.md, TEST-REPORT.md, CHANGE-BRIEF.md")
    rf.append(f"| {b['beat_id']} | {visual(b)} | {s['observation']} | {src} | {b['narration_text']} | {NEXT.get(b['beat_id'], '')} |")
(REEL / "RIFF.md").write_text("\n".join(rf) + "\n")
print(f"docs written; film {t:.1f} s")
