"""Write SHOTLIST.md from beat_sheet.json and evidence/media-provenance.json (no hand-copied intervals)."""
from common import REEL, FPS, load_json, render_frames

LABELS = {
    'B00': 'ClaudeComposerAsk · Reconstructed prompt (not a saved chat)',
    'B01': 'BrutalistHesitantWriter · one correction: look right → are the right size',
    'B02': 'Card · assignment requirements and the three props (CHANGE-BRIEF.md)',
    'B03': 'Card · My screenshot ×3 (Scene Statistics), status bars enlarged',
    'B04': 'Card · Excerpt from the Claude Code session (the Rock prompt) + My screenshot (the approval)',
    'B05': 'Source view · Blender Python, run through the MCP — not Godot · build_rock.py 309–319',
    'B06': 'Card · Blender MCP look render — captured by Claude Code (first build, Revision 1)',
    'B07': 'Card · My screenshot (the hand edit), title bar and rotation enlarged',
    'B08': 'Source view · Blender Python · build_crystal.py 472–478',
    'B09': 'Card · Blender MCP look render — captured by Claude Code (crystal)',
    'B10': 'Source view · Blender Python · build_chest.py 107–113 (line 134 as a note)',
    'B11': 'Card · Blender MCP look render — captured by Claude Code (chest, gold at metallic 1.0)',
    'B12': 'Source view · Blender Python · build_chest.py 377–390',
    'B13': 'Card · Recorded command output (.glb read on the reference copy of 8d8895c)',
    'B14': 'Card · My screenshot ×3 (prop room before the scene fixes)',
    'B15': 'GodotDevWorkbench · Godot editor reconstruction · prop_room.tscn 37–44',
    'B16': 'Godot Movie Maker capture · scripted camera · run-01 (+ Held frame)',
    'B17': 'GodotDevWorkbench · Godot editor reconstruction · test_a3_assets.gd 78–90',
    'B18': 'Card · Headless check output — not a render (reference copy of 8d8895c)',
    'B19': 'Card · What Claude got wrong · Known limitations (TEST-REPORT.md)',
    'B20': 'ClaudeVerdictArtifact',
    'B21': 'ClaudeComposerAsk · Your turn. · suggested prompt, not a saved chat',
    'B22': 'ClaudeTitleOutro (locked) · silent',
}


def main():
    sheet = load_json(REEL / 'beat_sheet.json')
    prov = load_json(REEL / 'evidence' / 'media-provenance.json')['beats']
    rows, t = [], 0.0
    for b in sheet['beats']:
        bid = b['beat_id']
        n = render_frames(b['actual_duration_s'])
        p = prov.get(bid, {})
        src = ''
        if 'take' in p:
            src = (f"{p['take']} {p['take_start_s']:.3f}–{p['take_end_s']:.3f} s (src frames {p['src_frame_start']}–"
                   f"{p['src_frame_end'] - 1}, every 2nd) + {p['held_frames']} held frames")
        elif 'source' in p:
            src = p['source']
        elif 'images' in p or 'image' in p:
            src = ', '.join(p.get('images') or [p['image']])
        elif 'log' in p:
            src = p['log']
        rows.append(f"| {bid} | {t:6.2f} | {n / FPS:5.2f} | {b['heading']} | {LABELS[bid]} | {src or '—'} |")
        t += n / FPS
    text = f"""# SHOTLIST — {sheet['metadata']['title']}

> Generated by `scripts/shotlist.py` from `beat_sheet.json` and `evidence/media-provenance.json`. Native 3840x2160, 30 fps. Total {t:.2f} s.

**Footage rule.** B16 is the whole Movie Maker take `capture/run-01.avi` (60 fps, scripted camera, gate in CAPTURE.md) at normal speed: every second source frame for 30 fps, then its final frame held to the narration's end, labelled **Held frame** on screen. The compiler never retimes, slows or center-cuts it. The scene is silent; Liam's narration is the only sound.

| Beat | Start s | Dur s | Heading | On screen / label | Source |
|---|---|---|---|---|---|
""" + '\n'.join(rows) + '\n'
    (REEL / 'SHOTLIST.md').write_text(text, encoding='utf-8')
    print(f'SHOTLIST.md: {len(rows)} beats, {t:.2f} s')


if __name__ == '__main__':
    main()
