def main():
    sheet = load_json(REEL / 'beat_sheet.json')
    prov = load_json(REEL / 'evidence' / 'media-provenance.json')['beats']
    rows, t = [], 0.0
    for b in sheet['beats']:
        bid = b['beat_id']
        n = render_frames(b['actual_duration_s'])
        p = prov.get(bid, {})
        src = p.get('source') or ', '.join(p.get('images', [])) or '—'
        rows.append(f"| {bid} | {t:6.2f} | {n / FPS:5.2f} | {b['heading']} | {LABELS[bid]} | {src} |")
        t += n / FPS
    text = f"""# SHOTLIST — {sheet['metadata']['title']}

> Generated by `scripts/shotlist.py` from `beat_sheet.json` and `evidence/media-provenance.json`. Native 3840x2160, 30 fps. Total {t:.2f} s.

**Image rule.** Gameplay (B04, B13, B19, and the two frames on B02) is `capture/run-01`: the real main scene at 3c37fe0, played by `capture/driver.gd` with scripted mouse and key input, recorded by Movie Maker in a window (640×360 at 30 fps) and shown ×5 nearest neighbour; each beat plays its interval at real speed, then a labelled ×0.25 replay, then a labelled hold. Strips are the author's committed fixture captures in `captures/` (preview scenes, not gameplay), cropped and enlarged with the factor stated. Code views are labelled reconstructions. Liam's narration is the only sound; game audio is not used; the final card is silent.

| Beat | Start s | Dur s | Heading | On screen / label | Source |
|---|---|---|---|---|---|
""" + '\n'.join(rows) + '\n'
    (REEL / 'SHOTLIST.md').write_text(text, encoding='utf-8')
    print(f'SHOTLIST.md: {len(rows)} beats, {t:.2f} s')


if __name__ == '__main__':
    main()
