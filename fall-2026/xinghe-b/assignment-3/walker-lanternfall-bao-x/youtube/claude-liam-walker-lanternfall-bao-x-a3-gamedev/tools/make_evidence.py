#!/usr/bin/env python3
"""Write gamedev-evidence.json (schema 1, teaching contract code-then-result-v1) for the Assignment 3 film.

Every authored file under godot/ (no .godot/, no .uid) is hashed and either tied to an Assignment 3 component or
excluded with a reason; excerpts are taken from the beat sheet's GodotDevWorkbench beats and re-read from disk; each
code beat is paired with the next beat's hashed result media.

    python3 tools/make_evidence.py [--game PATH]   (default: <repo>/godot)
"""
import hashlib, json, sys
from pathlib import Path

REEL = Path(__file__).resolve().parents[1]
GAME = Path(sys.argv[sys.argv.index("--game") + 1]).resolve() if "--game" in sys.argv else REEL.parents[1] / "godot"
SHA = (REEL / "FILM-SOURCE-REVISION.txt").read_text().strip()

COMPONENTS = {
    "lantern-gate": ("The Lantern Gate: six visible primitives and two Blender boxes named *-convcolonly, which Godot's "
                     "importer turns into collision-only static bodies (use_node_type_suffixes=true in the generated "
                     ".import); lantern_gate.gd puts both on physics layer 3 with mask 0. Shown as code (B12) and as a "
                     "real capture of the stand-in stopping at the base (B13).", ["B02", "B12", "B13"],
                     ["a3/lantern_gate.gd", "a3/lantern_gate.tscn", "a3/lantern_gate.glb", "a3/lantern_gate.glb.import"]),
    "supply-stack": ("The Supply Stack GLB exported from the MCP build: two crates and a 12-sided barrel, rotation and "
                     "scale applied in Blender (B05-B08), measured in Godot (B11).", ["B02", "B08", "B11"],
                     ["a3/supply_stack.glb", "a3/supply_stack.glb.import"]),
    "oil-shrine": ("The Lamp-oil Shrine GLB: plinth, stem and an icosphere gem, re-exported by Bao with File > Export "
                   "after his 20-degree hand edit of OilGem (B09); measured in Godot (B11).", ["B02", "B09", "B11"],
                   ["a3/oil_shrine.glb", "a3/oil_shrine.glb.import"]),
    "prop-room": ("The 3D prop room: floor, moon light, two practical lights, labels, the courier stand-in and the "
                  "A3-R3 orbit camera (B14, B15). session.gd belongs here only for its a3_room action (F4, lines "
                  "363-364 and 399); project.godot sets the 640 x 360 stretch the room's HUD label and drag input "
                  "pass through. The rest of session.gd is the Assignment 2 game.", ["B13", "B14", "B15"],
                  ["a3/lantern_gate_room.gd", "a3/lantern_gate_room.tscn", "game/session.gd", "project.godot"]),
    "a3-tests": ("Headless checks on the shared harness: test_a3_assets.gd (17: size, floor origin, +Y height, unit "
                 "scale, budgets, material names, room placement, a caught scale mutation), test_lantern_gate.gd (14: "
                 "colliders, layers, stop), test_a3_camera.gd (9: orbit, floor hiding, clamps, drag); "
                 "capture_a3_orbit.gd renders the front/behind/below evidence stills.", ["B10", "B11", "B15"],
                 ["tests/harness.gd", "tests/test_a3_assets.gd", "tests/test_lantern_gate.gd", "tests/test_a3_camera.gd",
                  "tests/capture_a3_orbit.gd"]),
}
A2 = ("Assignment 2's 2D game, unchanged by Assignment 3. It is explained component by component in the Assignment 2 "
      "film (youtube/claude-liam-walker-lanternfall-bao-x-gamedev); its 122 checks are re-run and reported in "
      "TEST-REPORT.md, not shown in this film.")
EXCLUDE_PREFIX = ("assets/", "audio/", "features/", "ui/")
EXCLUDE = {
    "game/game_state.gd": A2, "game/main.tscn": A2, "tests/test_logic.gd": A2, "tests/test_gameplay.gd": A2,
    "tests/test_audio.gd": A2,
    "tests/capture.gd": "Assignment 2 capture tool (character comparison row); not used by this film.",
    "tests/capture_map.gd": "Assignment 2 development tool (map overview image); not used by this film.",
    "tests/probe_balance.gd": "Assignment 2 balance bots; not part of the A3 room and not shown.",
    "tests/rasterize_storyboard.gd": "Assignment 2 storyboard rasteriser; not shown.",
    "tests/capture_lantern_gate.gd": ("Earlier A3 still-capture tool (evidence/a3/a3-assets-room.png, from the "
                                      "script-route build); superseded for this film by capture_a3_orbit.gd and the "
                                      "Movie Maker takes."),
}
ROLES = {".gd": "GDScript", ".tscn": "scene", ".godot": "project settings", ".glb": "Blender export (binary glTF)",
         ".import": "import settings sidecar (generated by Godot)"}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    sheet = json.loads((REEL / "beat_sheet.json").read_text())
    beats = sheet["beats"]
    inventory = sorted(p.relative_to(GAME).as_posix() for p in GAME.rglob("*")
                       if p.is_file() and not any(x in (".godot", ".git") for x in p.relative_to(GAME).parts) and p.suffix != ".uid")
    owner = {}
    for cid, (_e, _b, files) in COMPONENTS.items():
        for f in files:
            owner.setdefault(f, []).append(cid)
    exclusions = {p: (EXCLUDE.get(p) or A2) for p in inventory
                  if p not in owner and (p in EXCLUDE or p.startswith(EXCLUDE_PREFIX))}
    missing = [p for p in inventory if p not in owner and p not in exclusions]
    extra = [p for p in owner if p not in inventory]
    if missing or extra:
        raise SystemExit(f"inventory mismatch: unassigned {missing}, unknown {extra}")
    files = [{"path": p, "sha256": sha(GAME / p), "role": ROLES.get(Path(p).suffix, "file"), "component_ids": owner[p]}
             for p in inventory if p in owner]
    comps = [{"id": cid, "explanation": e, "beat_ids": b, "files": f} for cid, (e, b, f) in COMPONENTS.items()]
    excerpts, pairs = [], []
    for i, b in enumerate(beats):
        rem = (b.get("shot") or {}).get("remotion") or {}
        if not rem.get("pattern", "").startswith("GodotDevWorkbench") or not rem.get("props", {}).get("code"):
            continue
        p = rem["props"]
        path = p["path"].replace("res://", "")
        n = len(p["code"].split("\n"))
        text = "\n".join((GAME / path).read_text().splitlines()[p["startLine"] - 1:p["startLine"] - 1 + n])
        if text != p["code"]:
            raise SystemExit(f"{b['beat_id']}: displayed code differs from {path}")
        excerpts.append({"beat_id": b["beat_id"], "path": path, "start_line": p["startLine"],
                         "end_line": p["startLine"] + n - 1, "text": text})
        nxt = beats[i + 1]
        media = nxt["shot"].get("evidence_media")
        if not media:
            raise SystemExit(f"{b['beat_id']}: next beat {nxt['beat_id']} has no evidence media")
        pairs.append({"code_beat": b["beat_id"], "result_beat": nxt["beat_id"],
                      "observation": nxt.get("observation") or nxt["role_note"],
                      "media": {"path": media, "sha256": sha(REEL / media)}})
    data = {"schema_version": 1, "teaching_contract": "code-then-result-v1",
            "game": {"project_dir": "godot", "source_revision": SHA, "engine": "Godot 4.7.2.stable.official.ed1daf0bf"},
            "files": files, "components": comps, "excerpts": excerpts,
            "exclusions": [{"path": p, "reason": r} for p, r in sorted(exclusions.items())],
            "code_result_pairs": pairs}
    (REEL / "gamedev-evidence.json").write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"gamedev-evidence.json: {len(files)} files, {len(exclusions)} exclusions, {len(comps)} components, "
          f"{len(excerpts)} excerpts, {len(pairs)} code/result pairs")


if __name__ == "__main__":
    main()
