#!/usr/bin/env python3
"""collect_findings.py: gathers, from every laid-out film, the fact-check rows that CORRECTED a source claim or are still OPEN,
plus each film's CHECKS-REPORT "Found" paragraph, into FINDINGS-COLLECTED.md (generated; SERIES-PLAN.md's "What the layouts
found" is written from it by hand). Run:  python3 collect_findings.py
Everything is read from the films' own files, so the plan cannot drift from them."""
import re
import sys
from pathlib import Path

SERIES = Path(__file__).resolve().parent
sys.path.insert(0, str(SERIES))
import series_config as S  # noqa: E402

ROW = re.compile(r"^\|\s*(?P<n>[\w\-]+)\s*\|\s*(?P<beat>[^|]*)\|\s*(?P<claim>[^|]*)\|\s*(?P<verdict>CORRECTED|OPEN|PASS|EXEMPT)\s*\|\s*(?P<evidence>[^|]*)\|\s*(?P<action>[^|]*)\|?\s*$")


def short(s, n=420):
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def found_paragraph(path):
    if not path.exists():
        return ""
    for line in path.read_text().splitlines():
        if line.startswith("**Found.**"):
            return line[len("**Found.**"):].strip()
    return ""


def main():
    out = ["# Findings collected from the film folders (generated by collect_findings.py)\n",
           "**What this is.** For every laid-out film: the fact-check rows where running Godot (or reading the docs) CORRECTED a claim, the rows still OPEN, and the CHECKS-REPORT summary.",
           "**Why.** So SERIES-PLAN.md's \"What the layouts found\" is written from the films' own records, not from memory.",
           "**Found.** See below; counts per film are in the heading of each section.\n"]
    totals = {"films": 0, "rows": 0, "corrected": 0, "open": 0}
    for slug, title, group in S.FILMS:
        film = S.folder(slug)
        fc = film / "FACTCHECK.md"
        if not fc.exists():
            out.append(f"## {title}\n\nnot laid out yet.\n")
            continue
        rows = [m.groupdict() for m in (ROW.match(l) for l in fc.read_text().splitlines()) if m]
        corrected = [r for r in rows if r["verdict"] == "CORRECTED"]
        opened = [r for r in rows if r["verdict"] == "OPEN"]
        totals["films"] += 1
        totals["rows"] += len(rows)
        totals["corrected"] += len(corrected)
        totals["open"] += len(opened)
        out.append(f"## {title}  ({len(rows)} fact-check rows: {len(corrected)} CORRECTED, {len(opened)} OPEN)\n")
        fp = found_paragraph(film / "CHECKS-REPORT.md")
        if fp:
            out.append(f"*CHECKS-REPORT:* {short(fp, 900)}\n")
        for r in corrected:
            out.append(f"- **CORRECTED** ({r['beat'].strip()}): {short(r['claim'], 260)} → {short(r['evidence'])}")
        for r in opened:
            out.append(f"- **OPEN** ({r['beat'].strip()}): {short(r['claim'], 260)} → {short(r['evidence'])}")
        out.append("")
    out.insert(4, f"**Totals so far.** {totals['films']} films with a fact-check, {totals['rows']} rows, {totals['corrected']} CORRECTED, {totals['open']} OPEN.\n")
    (SERIES / "FINDINGS-COLLECTED.md").write_text("\n".join(out) + "\n")
    print(f"{totals['films']} films, {totals['rows']} rows, {totals['corrected']} corrected, {totals['open']} open -> FINDINGS-COLLECTED.md")


if __name__ == "__main__":
    main()
